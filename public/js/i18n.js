/** @type {'en'|'de'} */
let lang = 'en';

/** @param {string | undefined | null} navLang */
export function fromNavigator(navLang) {
  return String(navLang || '').toLowerCase().startsWith('de') ? 'de' : 'en';
}

/** Language from local storage, else from the browser. */
export function detectLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'en' || saved === 'de') return saved;
  } catch {
    /* storage blocked */
  }
  return fromNavigator(typeof navigator !== 'undefined' ? navigator.language : 'en');
}

/** @param {'en'|'de'} l @param {boolean} [persist] */
export function setLang(l, persist = false) {
  lang = l === 'de' ? 'de' : 'en';
  if (persist) {
    try {
      localStorage.setItem(STORE_KEY, lang);
    } catch {
      /* storage blocked */
    }
  }
}

export const getLang = () => lang;
export const locale = () => (lang === 'de' ? 'de-CH' : 'en-GB');

/** @param {string} key @param {Record<string, string | number>} [params] */
export function t(key, params = {}) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  const all = { app: APP_NAME, host: typeof location === 'undefined' ? '' : location.host, months: RETENTION_MONTHS, idle: IDLE_DAYS, perday: MAX_PER_DAY, ...params };
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in all ? String(all[/** @type {keyof typeof all} */ (k)]) : m));
}

/**
 * Text with singular/plural: uses `${key}_one` for n = 1, else `${key}_other` (same in both languages).
 * @param {string} key @param {number} n @param {Record<string, string | number>} [params]
 */
export function tn(key, n, params = {}) {
  return t(`${key}_${n === 1 ? 'one' : 'other'}`, { n, ...params });
}

/** Confirm word typed by the user: case-insensitive, Ä/Ö/Ü also as AE/OE/UE («LOESCHEN» = «LÖSCHEN»). @param {string} typed @param {string} word */
export function wordMatches(typed, word) {
  const fold = (/** @type {string} */ x) => x.trim().toUpperCase().replace(/Ä/g, 'AE').replace(/Ö/g, 'OE').replace(/Ü/g, 'UE');
  return fold(String(typed)) === fold(word);
}

/** Short weekday, 0 = Monday. @param {number} i */
export const weekdayShort = (i) => t('wd').split(',')[i];

/** Decimal number in the current language (42,5 / 42.5). @param {number} n */
export const num = (n) => (lang === 'de' ? String(n).replace('.', ',') : String(n));

/**
 * Fill static texts: data-i18n (text), data-i18n-aria (aria-label), data-i18n-placeholder (the last two
 * without soft hyphens).
 * @param {ParentNode} [root]
 */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(/** @type {string} */ (el.getAttribute('data-i18n')));
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', plain(t(/** @type {string} */ (el.getAttribute('data-i18n-aria')))));
  for (const el of root.querySelectorAll('[data-i18n-placeholder]'))
    el.setAttribute('placeholder', plain(t(/** @type {string} */ (el.getAttribute('data-i18n-placeholder')))));
  document.documentElement.lang = lang === 'de' ? 'de-CH' : 'en';
}
